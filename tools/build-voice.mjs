#!/usr/bin/env node
// Records Joshua's vocabulary, one word at a time, the way the film did it: an English voice reads
// each word in isolation, so every word carries the same flat stress once they're joined back up.
//
// Output: vendor/joshua-voice.js, which sets window.JOSHUA_VOICE = { word: base64 mp3, ... }.
// It ships with the app, so players on any device hear these recordings, not their own system voice.
//
// Needs macOS (`say` with the Daniel voice) and ffmpeg. Run from the project root:
//   node tools/build-voice.mjs          record missing words, keep existing ones
//   node tools/build-voice.mjs --check  only report words Joshua can say that aren't recorded
//   node tools/build-voice.mjs --fresh  re-record everything

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync, existsSync } from 'node:fs';
import { tmpdir, cpus } from 'node:os';
import { join } from 'node:path';
import { spawn } from 'node:child_process';

const VOICE = 'Daniel';
const RATE = 145; // words per minute for each isolated word ("B" in the listening test)
const OUT = 'vendor/joshua-voice.js';
const SOURCES = ['js/joshua.js', 'js/tictactoe.js', 'js/war.js', 'js/data.js', 'js/main.js'];

// Words the runtime produces itself when it spells out numbers (see spokenWords in js/audio.js).
const NUMBER_WORDS = `zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen
  fifteen sixteen seventeen eighteen nineteen twenty thirty forty fifty sixty seventy eighty ninety hundred
  thousand million first second third fourth fifth sixth seventh eighth ninth tenth twentieth thirtieth
  whopper`.split(/\s+/).filter(Boolean);

// Every all-caps string literal in the game is something Joshua might say.
function vocabulary() {
  const words = new Set(NUMBER_WORDS);
  for (const file of SOURCES) {
    const src = readFileSync(file, 'utf8').replace(/(^|\s)\/\/.*$/gm, '$1');
    for (const m of src.matchAll(/(['"`])((?:\\.|(?!\1).)*)\1/g)) {
      const text = m[2].replace(/\$\{[^}]*\}/g, ' ').replace(/\\[ntr]/g, ' ');
      // Joshua's lines are all caps; mixed-case strings are hints, code, or the player's words.
      if (!/[A-Z]{2,}/.test(text) || /[a-z]/.test(text)) continue;
      for (const w of tokens(text)) words.add(w);
    }
  }
  return [...words].sort();
}

// Must match tokenising in js/audio.js.
function tokens(text) {
  return (
    text
      .replace(/W\.O\.P\.R\./g, 'WHOPPER')
      .toLowerCase()
      .replace(/[’]/g, "'")
      .match(/[a-z]+(?:'[a-z]+)?/g) || []
  );
}

function run(cmd, args) {
  return new Promise((resolve, reject) => {
    const p = spawn(cmd, args, { stdio: ['ignore', 'ignore', 'pipe'] });
    let err = '';
    p.stderr.on('data', (d) => (err += d));
    p.on('close', (code) => (code === 0 ? resolve() : reject(new Error(`${cmd} failed: ${err}`))));
  });
}

async function record(word, dir) {
  const aiff = join(dir, `${word}.aiff`);
  const mp3 = join(dir, `${word}.mp3`);
  await run('say', ['-v', VOICE, '-r', String(RATE), '-o', aiff, word]);
  // Trim the silence say() leaves around the word, so words butt up against each other.
  const trim = 'silenceremove=start_periods=1:start_threshold=-40dB,areverse,silenceremove=start_periods=1:start_threshold=-40dB,areverse';
  await run('ffmpeg', ['-y', '-loglevel', 'error', '-i', aiff, '-af', trim, '-ar', '22050', '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '40k', mp3]);
  return readFileSync(mp3).toString('base64');
}

function loadExisting() {
  if (!existsSync(OUT)) return {};
  const src = readFileSync(OUT, 'utf8');
  return JSON.parse(src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1));
}

const args = process.argv.slice(2);
const vocab = vocabulary();
const bank = args.includes('--fresh') ? {} : loadExisting();
const missing = vocab.filter((w) => !bank[w]);

if (args.includes('--check')) {
  console.log(`${vocab.length} words in vocabulary, ${missing.length} not recorded`);
  if (missing.length) console.log(missing.join(' '));
  process.exit(missing.length ? 1 : 0);
}

execFileSync('say', ['-v', '?']).toString().includes(VOICE) || (console.error(`macOS voice "${VOICE}" not installed`), process.exit(1));

const dir = mkdtempSync(join(tmpdir(), 'joshua-'));
let done = 0;
const queue = missing.slice();
await Promise.all(
  Array.from({ length: Math.min(8, cpus().length) }, async () => {
    while (queue.length) {
      const w = queue.shift();
      bank[w] = await record(w, dir);
      if (++done % 25 === 0 || done === missing.length) console.log(`recorded ${done}/${missing.length}`);
    }
  })
);
rmSync(dir, { recursive: true, force: true });

const sorted = Object.fromEntries(Object.keys(bank).sort().map((k) => [k, bank[k]]));
writeFileSync(
  OUT,
  `// Generated by tools/build-voice.mjs: ${Object.keys(sorted).length} words, voice "${VOICE}" at ${RATE} wpm.\n` +
    `window.JOSHUA_VOICE = ${JSON.stringify(sorted)};\n`
);
console.log(`wrote ${OUT}: ${Object.keys(sorted).length} words, ${(readFileSync(OUT).length / 1024).toFixed(0)} KB`);
